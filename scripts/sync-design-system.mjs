// Copies main-app's design-system theme into playground/theme/, so the
// playground renders the shadcn bar with the app's exact tokens, type roles
// and Tailwind scales.
//
//   MAIN_APP_DIR=../../awtomated/main-app yarn ui:sync
//
// The shadcn primitives in src/shadcn/ui/ and src/shadcn/lib/utils.js are
// copies of the app's design-system files too (see their headers); this
// script lists them so a drift is visible, but doesn't overwrite them, since
// they carry small local changes marked "filter-bar:".
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const appDir = resolve(repoRoot, process.env.MAIN_APP_DIR ?? '../../awtomated/main-app');
const ds = join(appDir, 'src/design-system');
const out = join(repoRoot, 'playground/theme');

if (!existsSync(ds)) {
  console.error(`main-app design system not found at ${ds}. Set MAIN_APP_DIR.`);
  process.exit(1);
}
mkdirSync(out, { recursive: true });

copyFileSync(join(ds, 'styles/tokens.css'), join(out, 'tokens.css'));
copyFileSync(join(ds, 'styles/theme.css'), join(out, 'theme.css'));
copyFileSync(join(appDir, 'public/assets/tailwind-base.css'), join(out, 'tailwind-base.css'));
// The app's global element styles (html/body font, size, letter spacing).
copyFileSync(join(appDir, 'src/styles/app-base.css'), join(out, 'app-base.css'));

// app-utilities.css minus what only makes sense inside the app: its own
// Tailwind import and source globs, and the theme.css import (the playground
// imports that itself).
const utilities = readFileSync(join(appDir, 'src/styles/app-utilities.css'), 'utf8')
  .split('\n')
  .filter(
    (line) =>
      !/^@import "tailwindcss\/utilities\.css"/.test(line) &&
      !/^@source /.test(line) &&
      !/^@import "\.\.\/design-system\/styles\/theme\.css"/.test(line)
  )
  .join('\n');
writeFileSync(
  join(out, 'app-theme.css'),
  `/* Generated by scripts/sync-design-system.mjs from main-app src/styles/app-utilities.css. */\n${utilities}`
);

console.log(`Theme copied from ${appDir} into playground/theme/.`);
console.log('Primitives to compare by hand (src/shadcn/ui ↔ design-system/components/ui):');
['button', 'popover', 'spinner'].forEach((name) => console.log(`  - ${name}`));
